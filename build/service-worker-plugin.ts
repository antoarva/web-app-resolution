/**
 * Generates the offline service worker at build time.
 *
 * Replaces vite-plugin-pwa, whose workbox dependency requires a newer Node than
 * this project targets. The job is small enough to do directly: collect every
 * file the build emitted, write them into a precache manifest, and emit a
 * worker that serves them cache-first.
 *
 * The app makes no network requests at runtime, so once the precache is
 * populated the service worker can satisfy everything from it — including the
 * WebAssembly engine, which is what makes the simulation work offline.
 */

import type { Plugin } from 'vite';

export interface ServiceWorkerOptions {
  /** Bumped automatically per build so clients pick up new assets. */
  cacheName?: string;
  /** Extra URLs to precache beyond the build output. */
  additional?: string[];
}

const PRECACHE_EXTENSIONS = /\.(js|css|html|wasm|woff2?|ttf|svg|png|jpg|json|ico)$/i;

export function serviceWorkerPlugin(options: ServiceWorkerOptions = {}): Plugin {
  const buildId = Date.now().toString(36);
  const cacheName = `${options.cacheName ?? 'envelop'}-${buildId}`;

  return {
    name: 'envelop:service-worker',
    apply: 'build',

    generateBundle(_config, bundle) {
      const assets = Object.keys(bundle)
        .filter((fileName) => PRECACHE_EXTENSIONS.test(fileName))
        .map((fileName) => `/${fileName}`);

      const precache = [
        '/',
        '/index.html',
        ...assets,
        ...(options.additional ?? []),
      ];
      // Deduplicate: index.html appears both in the bundle and as the root.
      const manifest = [...new Set(precache)];

      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: workerSource(cacheName, manifest),
      });

      this.emitFile({
        type: 'asset',
        fileName: 'manifest.webmanifest',
        source: JSON.stringify({
          name: 'Envelop - Web-Based EnergyPlus Editor',
          short_name: 'Envelop',
          description: 'Offline, WebAssembly-powered EnergyPlus IDF editor',
          start_url: '/',
          display: 'standalone',
          background_color: '#ffffff',
          theme_color: '#0f172a',
          icons: [{ src: '/favicon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' }],
        }, null, 2),
      });
    },
  };
}

function workerSource(cacheName: string, precache: string[]): string {
  return `/* Generated by envelop:service-worker. Do not edit. */
const CACHE = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(precache, null, 2)};

/*
 * Ignore Vary when matching.
 *
 * A precached entry is stored from a plain Request, but the browser later asks
 * for the same file as a module import or a stylesheet, with different headers.
 * If the server attached a Vary header (vite preview sends one), the default
 * match compares those headers and misses — the file sits in the cache and is
 * never found, which offline looks exactly like a 504.
 *
 * Every asset here is content-hashed, so a URL identifies its bytes completely
 * and there is nothing for Vary to negotiate.
 */
const MATCH_OPTIONS = { ignoreVary: true };

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // Add entries individually: one 404 in addAll() would reject the whole
    // install and leave the app without an offline cache.
    await Promise.all(PRECACHE.map(async (url) => {
      try {
        await cache.add(new Request(url, { cache: 'reload' }));
      } catch (error) {
        console.warn('[envelop-sw] could not precache', url, error);
      }
    }));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name !== CACHE).map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Navigations resolve to the SPA shell so deep links work offline.
  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cached = await caches.match('/index.html', MATCH_OPTIONS);
      if (cached) return cached;
      try {
        return await fetch(request);
      } catch {
        return new Response('Envelop is offline and has not been cached yet.', {
          status: 503, headers: { 'Content-Type': 'text/plain' },
        });
      }
    })());
    return;
  }

  event.respondWith((async () => {
    const cached = await caches.match(request, MATCH_OPTIONS);
    if (cached) return cached;
    try {
      const response = await fetch(request);
      // Cache same-origin successes so a first visit warms anything missed.
      if (response.ok && response.type === 'basic') {
        const cache = await caches.open(CACHE);
        cache.put(request, response.clone());
      }
      return response;
    } catch (error) {
      return new Response('Offline and not cached: ' + url.pathname, {
        status: 504, headers: { 'Content-Type': 'text/plain' },
      });
    }
  })());
});
`;
}
